"""Recording a game's full soundtrack by running it in MAME.

FM/sequenced music (YM2151, YM2203, YM2612, QSound sequences, ...) is not
stored as audio in the ROM; it is generated by the sound CPU's driver at run
time.  The faithful way to capture it is to let MAME emulate the board and
write its mixed output with ``-wavwrite``.
"""

from __future__ import annotations

import os
import subprocess
import sys


def build_command(mame_exe: str, game: str, wav_out: str, seconds: int,
                  rompath: str = "", lua_script: str = "", mute: bool = True,
                  extra_args: str = ""):
    cmd = [mame_exe, game,
           "-wavwrite", wav_out,
           "-seconds_to_run", str(int(seconds)),
           "-nothrottle",          # run as fast as the PC allows
           "-skip_gameinfo",
           "-window",
           "-video", "none"]
    if mute:
        cmd += ["-volume", "-32"]
    if rompath:
        cmd += ["-rompath", rompath]
    if lua_script:
        cmd += ["-autoboot_script", lua_script]
    if extra_args:
        cmd += extra_args.split()
    return cmd


def run(cmd, log=None) -> int:
    """Run MAME, streaming its console output to ``log`` (a callable)."""
    kwargs = {}
    if sys.platform == "win32":
        kwargs["creationflags"] = 0x08000000  # CREATE_NO_WINDOW
    cwd = os.path.dirname(cmd[0]) or None   # MAME looks for mame.ini/BIOS here
    proc = subprocess.Popen(cmd, cwd=cwd, stdout=subprocess.PIPE,
                            stderr=subprocess.STDOUT, text=True,
                            errors="replace", **kwargs)
    for line in proc.stdout:
        if log:
            log(line.rstrip())
    return proc.wait()


LUA_TEMPLATE = """-- Arcade Music Extractor: sound-test driver for MAME's -autoboot_script.
-- Writes each sound code into the sound latch, waits, then moves on, so the
-- whole soundtrack ends up in one -wavwrite recording that can be split.
-- Fill in the CPU tag, latch address and codes for your game (the MAME
-- debugger or the game's own sound test will show the right values).

local cpu_tag   = ":maincpu"   -- CPU that writes sound commands
local latch     = 0x000000     -- address of the sound latch / command port
local codes     = { 0x01, 0x02, 0x03 }  -- sound codes to play
local seconds   = 120          -- how long to let each track run
local silence   = 0x00         -- code that stops music (if the driver has one)
local start_at  = 10           -- seconds to wait for the game to boot

local space = manager.machine.devices[cpu_tag].spaces["program"]
local idx, next_t = 0, start_at

local function tick()
  local now = manager.machine.time.seconds
  if now < next_t then return end
  if idx > 0 then space:write_u8(latch, silence) end
  idx = idx + 1
  if idx > #codes then manager.machine:exit() return end
  space:write_u8(latch, codes[idx])
  next_t = now + seconds + 2
end

-- keep the subscription in a global so it is not garbage collected
if emu.add_machine_frame_notifier then
  ame_subscription = emu.add_machine_frame_notifier(tick)
else
  emu.register_frame_done(tick)
end
"""
